// --- Low-Level PCF8574 I2C Write Function ---
void pcf8574_write(uint8_t data) {
    // 1. Generate Start Condition
    I2C1->CR1 |= (1 << 8);
    while (!(I2C1->SR1 & (1 << 0))); // Wait for Start Bit (SB)

    // 2. Send 7-bit I2C Address + Write bit (0)
    I2C1->DR = (0x27 << 1);
    while (!(I2C1->SR1 & (1 << 1))); // Wait for ADDR flag

    // 3. Clear ADDR flag (Read SR1 then SR2)
    volatile int dummy = I2C1->SR1;
    dummy = I2C1->SR2;

    // 4. Wait for Transmit Data Register Empty (TXE)
    while (!(I2C1->SR1 & (1 << 7)));
    I2C1->DR = data; // Send the given byte

    // 5. Wait for Byte Transfer Finished (BTF)
    while (!(I2C1->SR1 & (1 << 2)));

    // 6. Generate Stop Condition
    I2C1->CR1 |= (1 << 9);
    while ((I2C1->CR1 & (1 << 9))); // Wait until STOP clears
}

// --- LCD Nibble Latching with EN Pulse ---
void lcd_send_nibble(uint8_t nibble, uint8_t rs) {
    uint8_t out_data = 0;

    out_data = (nibble & 0xF0); // Map 4 bits to upper nibble (P4-P7), this is where the actual data and command bits are
    out_data |= (1 << 3);       // Backlight ON (P3 = 1)

    if (rs) {
        out_data |= (1 << 0);   // RS = 1 for Data
    } else {
        out_data &= ~(1 << 0);  // RS = 0 for Command
    }

    // Pulse EN High
    pcf8574_write(out_data | (1 << 2));
    for (volatile int d = 0; d < 100; d++);

    // Pulse EN Low (Latches the data into the LCD)
    pcf8574_write(out_data & ~(1 << 2));
    for (volatile int d = 0; d < 100; d++);
    //high and low are done because the LCD latches data only on falling edge
}


